"""Build a consumer-driven spec from field reads and recorded snapshots."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import yaml

from a2a_spec.infer.consumer import ConsumerReads
from a2a_spec.snapshot.store import Snapshot


@dataclass(frozen=True)
class InferredSpec:
    """A generated spec plus what the generator could not be sure about."""

    data: dict[str, Any]
    header: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_yaml(self) -> str:
        """Render the spec as YAML, with the header as leading comments."""
        comments = "".join(f"# {line}\n" for line in self.header)
        return comments + yaml.safe_dump({"spec": self.data}, sort_keys=False)


def infer_spec(
    producer: str,
    consumer: str,
    reads: ConsumerReads,
    snapshots: list[Snapshot],
    name: str | None = None,
) -> InferredSpec:
    """Infer the structural contract a consumer needs from a producer.

    Only fields the consumer reads become part of the contract, so the
    producer stays free to change everything else. A field is required
    when the consumer reads it with ``data["key"]``, or when the producer
    sent it in every recorded snapshot: a consumer that falls back to a
    default via ``.get()`` would otherwise degrade silently if the field
    disappeared. Types come from the recorded values.
    """
    warnings = list(reads.warnings)
    required: list[str] = []
    properties: dict[str, Any] = {}
    header = [
        f"Generated by 'a2aspec infer' from {reads.source} and "
        f"{len(snapshots)} {producer} snapshot(s). Review before committing.",
    ]

    for name_ in reads.fields:
        field_reads = [r for r in reads.reads if r.name == name_]
        strict = any(r.strict for r in field_reads)
        lines = ", ".join(str(r.line) for r in field_reads)
        values = [s.output_data[name_] for s in snapshots if name_ in s.output_data]
        missing = sorted(s.scenario for s in snapshots if name_ not in s.output_data)

        if not values:
            warnings.append(
                f"'{name_}' is read by {consumer} (line {lines}) "
                f"but {producer} never sent it in any snapshot"
            )
        elif missing and strict:
            warnings.append(
                f"'{name_}' is read with [] by {consumer} (line {lines}) "
                f"but missing in: {', '.join(missing)}"
            )

        if strict or (values and not missing):
            required.append(name_)
        properties[name_] = _schema_for(values)
        status = "required" if name_ in required else "optional"
        header.append(f"  {name_}: {status}, read at line {lines}")

    data = {
        "name": name or f"{producer}-to-{consumer}",
        "version": "1.0",
        "producer": producer,
        "consumer": consumer,
        "description": f"Fields {consumer} reads from {producer} (inferred)",
        "structural": {"type": "object", "required": required, "properties": properties},
    }
    return InferredSpec(data=data, header=header, warnings=warnings)


def _schema_for(values: list[Any]) -> dict[str, Any]:
    types = list(dict.fromkeys(_json_type(v) for v in values))
    if "integer" in types and "number" in types:
        types.remove("integer")
    if not types:
        return {}
    return {"type": types[0] if len(types) == 1 else types}


def _json_type(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "array"
    return "object"
