"""Build a consumer-driven spec from field reads and recorded snapshots."""

from __future__ import annotations

from collections.abc import Collection
from dataclasses import dataclass, field
from typing import Any

import yaml

from agent_handshake.infer.consumer import ConsumerReads
from agent_handshake.infer.paths import ITEMS, dotted
from agent_handshake.snapshot.store import Snapshot


@dataclass(frozen=True)
class InferredSpec:
    """A generated spec plus what the generator could not be sure about.

    ``missing`` lists fields the consumer reads that the producer sent in no
    snapshot. They are errors: the spec must not be written.
    """

    data: dict[str, Any]
    header: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)

    def to_yaml(self) -> str:
        """Render the spec as YAML, with the header as leading comments."""
        comments = "".join(f"# {line}\n" for line in self.header)
        return comments + yaml.safe_dump({"spec": self.data}, sort_keys=False)


def infer_spec(
    producer: str,
    consumer: str,
    reads: ConsumerReads,
    snapshots: list[Snapshot],
    name: str | None = None,
    allow_missing: Collection[str] = (),
) -> InferredSpec:
    """Infer the structural contract a consumer needs from a producer.

    Only fields the consumer reads become part of the contract, so the
    producer stays free to change everything else. Nested reads such as
    ``data["customer"]["tier"]`` give nested object schemas. A field is
    required when the consumer reads it with ``data["key"]``, or when the
    producer sent it in every recorded snapshot that has its parent: a
    consumer that falls back to a default via ``.get()`` would otherwise
    degrade silently if the field disappeared. Types come from the
    recorded values.

    A field the producer sent in no snapshot is an error in ``missing``,
    because typing it as optional would accept a broken producer. Dotted
    paths in ``allow_missing`` are fields absent on purpose; they stay
    optional with a warning.
    """
    warnings = list(reads.warnings)
    header = [
        f"Generated by 'handshake infer' from {reads.source} and "
        f"{len(snapshots)} {producer} snapshot(s). Review before committing.",
    ]
    outputs = [(s.scenario, s.output_data) for s in snapshots]
    read_at: dict[str, list[int]] = {}
    never_sent: list[tuple[str, str]] = []
    fields = _object_schema(
        (), outputs, reads, producer, consumer, header, warnings, read_at, never_sent
    )
    missing = [message for label, message in never_sent if label not in allow_missing]
    warnings += [
        f"{message}; allowed by --allow-missing"
        for label, message in never_sent
        if label in allow_missing
    ]
    labels = {label for label, _ in never_sent}
    allowed = [label for label in dict.fromkeys(allow_missing) if label in labels]
    warnings += [
        f"--allow-missing '{label}' names no field that is missing from every snapshot"
        for label in allow_missing
        if label not in labels
    ]

    data: dict[str, Any] = {
        "name": name or f"{producer}-to-{consumer}",
        "version": "1.0",
        "producer": producer,
        "consumer": consumer,
        "description": f"Fields {consumer} reads from {producer} (inferred)",
        "inferred_from": reads.source,
        "read_at": read_at,
    }
    if reads.warnings:
        data["reads_unknown_keys"] = True
    if allowed:
        data["allow_missing"] = allowed
    data["structural"] = {
        "type": "object",
        "required": fields.get("required", []),
        "properties": fields["properties"],
    }
    return InferredSpec(data=data, header=header, warnings=warnings, missing=missing)


def _object_schema(
    parent: tuple[str, ...],
    objects: list[tuple[str, Any]],
    reads: ConsumerReads,
    producer: str,
    consumer: str,
    header: list[str],
    warnings: list[str],
    read_at: dict[str, list[int]],
    never_sent: list[tuple[str, str]],
) -> dict[str, Any]:
    """Schema for the keys the consumer reads below ``parent``.

    Header lines, warnings and the read lines per dotted path are added to
    ``header``, ``warnings`` and ``read_at``; keys the producer never sent go
    to ``never_sent`` as (dotted path, message).

    ``objects`` holds the value at ``parent`` in each snapshot that has it,
    by scenario (for list items, every item of the list). Only dict values
    can carry keys.
    """
    depth = len(parent)
    keys = list(
        dict.fromkeys(
            r.path[depth] for r in reads.reads if len(r.path) > depth and r.path[:depth] == parent
        )
    )
    dicts = [(scenario, obj) for scenario, obj in objects if isinstance(obj, dict)]
    required: list[str] = []
    properties: dict[str, Any] = {}

    for key in keys:
        path = (*parent, key)
        below = [r for r in reads.reads if r.path[: depth + 1] == path]
        strict = any(r.strict[depth] for r in below)
        lines = ", ".join(str(n) for n in sorted({r.line for r in below}))
        label = dotted(path)
        present = [(scenario, obj[key]) for scenario, obj in dicts if key in obj]
        missing = sorted({scenario for scenario, obj in dicts if key not in obj})

        # When the parent itself was never sent, the error about it covers this key.
        # A parent that was sent but never as an object cannot carry the key either.
        never = (objects or not parent) and not present
        if never:
            never_sent.append(
                (
                    label,
                    f"'{label}' is read by {consumer} (line {lines}) "
                    f"but {producer} never sent it in any snapshot",
                )
            )
        elif missing and strict:
            warnings.append(
                f"'{label}' is read with [] by {consumer} (line {lines}) "
                f"but missing in: {', '.join(missing)}"
            )

        # A never-sent key is an error, or optional when --allow-missing names it.
        if not never and (strict or (present and not missing)):
            required.append(key)
        status = "required" if key in required else "optional"
        header.append(f"  {label}: {status}, read at line {lines}")
        read_at[label] = sorted({r.line for r in below})

        schema = _schema_for([value for _, value in present])
        deeper = [r for r in below if len(r.path) > depth + 1]
        if deeper and all(r.path[depth + 1] == ITEMS for r in deeper):
            # The consumer reads the items of this list: describe one item.
            items = [(s, item) for s, value in present if isinstance(value, list) for item in value]
            item_schema: dict[str, Any] = {}
            if any(len(r.path) > depth + 2 for r in deeper):
                item_schema = {"type": "object"}
            item_schema.update(
                _object_schema(
                    (*path, ITEMS),
                    items,
                    reads,
                    producer,
                    consumer,
                    header,
                    warnings,
                    read_at,
                    never_sent,
                )
            )
            schema = {"type": "array", "items": item_schema}
        elif deeper:
            schema = schema or {"type": "object"}
            schema.update(
                _object_schema(
                    path, present, reads, producer, consumer, header, warnings, read_at, never_sent
                )
            )
        properties[key] = schema

    if required:
        return {"required": required, "properties": properties}
    return {"properties": properties}


def _schema_for(values: list[Any]) -> dict[str, Any]:
    types = list(dict.fromkeys(_json_type(v) for v in values))
    if "integer" in types and "number" in types:
        types.remove("integer")
    if not types:
        return {}
    return {"type": types[0] if len(types) == 1 else types}


def _json_type(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "array"
    return "object"
