"""Tests for CLI infer command."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from agent_handshake.cli.main import app
from agent_handshake.spec.loader import load_spec

runner = CliRunner()

CONSUMER = """
async def resolution_agent(data: dict) -> dict:
    category = data.get("category", "general")
    return {"resolution": category, "urgent": data["priority"] == "high"}
"""


def _project(tmp_path: Path, with_snapshot: bool = True) -> Path:
    (tmp_path / "resolution.py").write_text(CONSUMER)
    if with_snapshot:
        snaps = tmp_path / "snapshots" / "triage-agent"
        snaps.mkdir(parents=True)
        (snaps / "billing_abc123.json").write_text(
            json.dumps(
                {
                    "fingerprint": "abc123",
                    "agent_id": "triage-agent",
                    "scenario": "billing",
                    "input": {"message": "charged twice"},
                    "output": {"category": "billing", "priority": "high", "summary": "x"},
                }
            )
        )
    config = tmp_path / "handshake.yaml"
    config.write_text(
        f'project_name: test\nspecs_dir: "{(tmp_path / "specs").as_posix()}"\n'
        f'storage:\n  path: "{(tmp_path / "snapshots").as_posix()}"\n'
    )
    return config


def _flat(text: str) -> str:
    """Undo rich's line wrapping so assertions do not depend on terminal width."""
    return " ".join(text.split())


def _args(tmp_path: Path, config: Path, *extra: str) -> list[str]:
    return [
        "infer",
        "--config",
        str(config),
        "--producer",
        "triage-agent",
        "--consumer",
        "resolution-agent",
        "--source",
        f"{tmp_path / 'resolution.py'}:resolution_agent",
        *extra,
    ]


class TestCliInfer:
    def test_writes_loadable_spec(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        result = runner.invoke(app, _args(tmp_path, config))
        assert result.exit_code == 0, result.output

        spec = load_spec(tmp_path / "specs" / "triage-agent-to-resolution-agent.yaml")
        assert spec.structural.required == ["category", "priority"]
        assert set(spec.structural.properties) == {"category", "priority"}

    def test_stdout(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        result = runner.invoke(app, _args(tmp_path, config, "--out", "-", "--name", "t2r"))
        assert result.exit_code == 0, result.output
        assert "name: t2r" in result.stdout
        assert not (tmp_path / "specs").exists()

    def test_refuses_overwrite_without_force(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        out = tmp_path / "spec.yaml"
        out.write_text("keep me")
        result = runner.invoke(app, _args(tmp_path, config, "--out", str(out)))
        assert result.exit_code == 1
        assert "--force" in _flat(result.output)
        assert out.read_text() == "keep me"

        result = runner.invoke(app, _args(tmp_path, config, "--out", str(out), "--force"))
        assert result.exit_code == 0, result.output
        assert out.read_text().startswith("# Generated by 'handshake infer'")

    def test_no_snapshots(self, tmp_path: Path) -> None:
        config = _project(tmp_path, with_snapshot=False)
        result = runner.invoke(app, _args(tmp_path, config))
        assert result.exit_code == 1
        assert "handshake record" in _flat(result.output)

    def test_bad_source_ref(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        args = _args(tmp_path, config)
        args[args.index("--source") + 1] = "resolution.py"
        result = runner.invoke(app, args)
        assert result.exit_code == 1
        assert "path/to/file.py:function" in _flat(result.output)

    def test_consumer_reading_nothing(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        (tmp_path / "resolution.py").write_text("def resolution_agent(d):\n    return helper(d)\n")
        result = runner.invoke(app, _args(tmp_path, config))
        assert result.exit_code == 1
        assert "reads no fields" in _flat(result.output)
        assert "is used as a whole" in _flat(result.output)


class TestCliInferCheck:
    def _inferred(self, tmp_path: Path) -> Path:
        config = _project(tmp_path)
        result = runner.invoke(app, _args(tmp_path, config))
        assert result.exit_code == 0, result.output
        return config

    def test_records_inferred_from(self, tmp_path: Path) -> None:
        self._inferred(tmp_path)
        spec = load_spec(tmp_path / "specs" / "triage-agent-to-resolution-agent.yaml")
        assert spec.inferred_from == f"{(tmp_path / 'resolution.py').as_posix()}:resolution_agent"

    def test_check_passes_when_current(self, tmp_path: Path) -> None:
        config = self._inferred(tmp_path)
        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 0, result.output
        assert "OK" in result.output and "triage-agent-to-resolution-agent" in result.output

    def test_check_fails_when_consumer_reads_new_field(self, tmp_path: Path) -> None:
        config = self._inferred(tmp_path)
        consumer = tmp_path / "resolution.py"
        consumer.write_text(consumer.read_text().replace('data["priority"]', 'data["urgency"]'))
        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 1
        out = _flat(result.output)
        assert "FAIL triage-agent-to-resolution-agent" in out
        assert "resolution_agent reads 'urgency' (line 4), which the spec does not cover" in out
        assert "WARN: the spec covers 'priority', which resolution_agent no longer reads" in out
        assert (
            "Regenerate: handshake infer --producer triage-agent --consumer resolution-agent" in out
        )

    def test_check_without_inferred_specs(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        (tmp_path / "specs").mkdir()
        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 0
        assert "No inferred specs to check" in _flat(result.output)

    def test_check_reports_missing_consumer(self, tmp_path: Path) -> None:
        config = self._inferred(tmp_path)
        (tmp_path / "resolution.py").unlink()
        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 1
        assert "Consumer source not found" in _flat(result.output)

    def test_generate_requires_arguments(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        result = runner.invoke(app, ["infer", "--config", str(config)])
        assert result.exit_code == 2
        assert "--producer, --consumer and --source are required" in _flat(result.output)


NESTED_CONSUMER = """
def resolution_agent(data: dict) -> dict:
    customer = data["customer"]
    return {"tier": customer.get("tier"), "urgent": data["priority"] == "high"}
"""


class TestCliInferNested:
    def test_nested_spec_and_check(self, tmp_path: Path) -> None:
        config = _project(tmp_path)
        snapshot = tmp_path / "snapshots" / "triage-agent" / "billing_abc123.json"
        data = json.loads(snapshot.read_text())
        data["output"]["customer"] = {"tier": "pro", "region": "eu"}
        snapshot.write_text(json.dumps(data))
        consumer = tmp_path / "resolution.py"
        consumer.write_text(NESTED_CONSUMER)

        result = runner.invoke(app, _args(tmp_path, config))
        assert result.exit_code == 0, result.output
        spec = load_spec(tmp_path / "specs" / "triage-agent-to-resolution-agent.yaml")
        assert spec.structural.required == ["customer", "priority"]
        assert spec.structural.properties["customer"] == {
            "type": "object",
            "required": ["tier"],
            "properties": {"tier": {"type": "string"}},
        }

        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 0, result.output

        consumer.write_text(NESTED_CONSUMER.replace('customer.get("tier")', 'customer["region"]'))
        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 1
        out = _flat(result.output)
        assert "reads 'customer.region' (line 4), which the spec does not cover" in out
        assert (
            "WARN: the spec covers 'customer.tier', which resolution_agent no longer reads" in out
        )


TS_CONSUMER = """
export async function resolutionAgent(ticket: Triage): Promise<Reply> {
  const tier = ticket.customer?.tier ?? "free";
  return { tier, urgent: ticket.priority === "high" };
}
"""


class TestCliInferTypeScript:
    def test_spec_and_check_from_typescript(self, tmp_path: Path) -> None:
        pytest.importorskip("tree_sitter_typescript", reason="needs the typescript extra")
        config = _project(tmp_path)
        snapshot = tmp_path / "snapshots" / "triage-agent" / "billing_abc123.json"
        data = json.loads(snapshot.read_text())
        data["output"]["customer"] = {"tier": "pro"}
        snapshot.write_text(json.dumps(data))
        consumer = tmp_path / "resolution.ts"
        consumer.write_text(TS_CONSUMER)
        args = _args(tmp_path, config)
        args[args.index("--source") + 1] = f"{consumer}:resolutionAgent"

        result = runner.invoke(app, args)
        assert result.exit_code == 0, result.output
        spec = load_spec(tmp_path / "specs" / "triage-agent-to-resolution-agent.yaml")
        assert spec.inferred_from == f"{consumer.as_posix()}:resolutionAgent"
        assert spec.structural.required == ["customer", "priority"]
        assert spec.structural.properties["customer"]["required"] == ["tier"]

        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 0, result.output

        consumer.write_text(TS_CONSUMER.replace("ticket.priority", "ticket.urgency"))
        result = runner.invoke(app, ["infer", "--check", "--config", str(config)])
        assert result.exit_code == 1
        assert "reads 'urgency' (line 4), which the spec does not cover" in _flat(result.output)
