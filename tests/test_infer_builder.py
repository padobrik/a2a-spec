"""Tests for consumer-driven spec inference."""

from __future__ import annotations

from typing import Any

import yaml

from agent_handshake.infer.builder import infer_spec
from agent_handshake.infer.consumer import ConsumerReads, FieldRead
from agent_handshake.snapshot.fingerprint import Fingerprint
from agent_handshake.snapshot.store import Snapshot
from agent_handshake.spec.schema import Spec
from agent_handshake.spec.validator import validate_output


def _snap(scenario: str, output: dict[str, Any]) -> Snapshot:
    fp = Fingerprint(agent_id="triage", input_hash=scenario)
    return Snapshot(fingerprint=fp, scenario=scenario, input_data={}, output_data=output)


def _strict(name: str, strict: bool | tuple[bool, ...]) -> tuple[bool, ...]:
    """One flag per key; a single bool applies to the last key, the parents are strict."""
    if isinstance(strict, tuple):
        return strict
    return (True,) * name.count(".") + (strict,)


def _reads(
    *reads: tuple[str, int, bool | tuple[bool, ...]], warnings: list[str] | None = None
) -> ConsumerReads:
    return ConsumerReads(
        source="res.py:run",
        param="data",
        reads=[FieldRead(tuple(n.split(".")), line, _strict(n, s)) for n, line, s in reads],
        warnings=warnings or [],
    )


SNAPS = [
    _snap("a", {"category": "billing", "confidence": 0.9, "tags": ["x"], "unused": 1}),
    _snap("b", {"category": "shipping", "confidence": 1, "note": None}),
]


class TestInferSpec:
    def test_only_read_fields_become_contract(self) -> None:
        spec = infer_spec("triage", "res", _reads(("category", 3, True)), SNAPS)
        props = spec.data["structural"]["properties"]
        assert list(props) == ["category"]
        assert props["category"] == {"type": "string"}

    def test_always_sent_optional_read_is_required(self) -> None:
        spec = infer_spec("triage", "res", _reads(("category", 3, False)), SNAPS)
        assert spec.data["structural"]["required"] == ["category"]

    def test_sometimes_sent_optional_read_is_optional(self) -> None:
        spec = infer_spec("triage", "res", _reads(("tags", 3, False)), SNAPS)
        assert spec.data["structural"]["required"] == []
        assert spec.warnings == []

    def test_strict_read_missing_in_snapshot_warns(self) -> None:
        spec = infer_spec("triage", "res", _reads(("tags", 7, True)), SNAPS)
        assert spec.data["structural"]["required"] == ["tags"]
        assert spec.warnings == ["'tags' is read with [] by res (line 7) but missing in: b"]

    def test_never_sent_field_warns(self) -> None:
        spec = infer_spec("triage", "res", _reads(("issue_type", 4, False)), SNAPS)
        assert spec.data["structural"]["properties"]["issue_type"] == {}
        assert "never sent it" in spec.warnings[0]

    def test_types(self) -> None:
        reads = _reads(("confidence", 1, True), ("note", 2, False), ("tags", 3, False))
        props = infer_spec("triage", "res", reads, SNAPS).data["structural"]["properties"]
        assert props["confidence"] == {"type": "number"}
        assert props["note"] == {"type": "null"}
        assert props["tags"] == {"type": "array"}

    def test_mixed_types_listed(self) -> None:
        snaps = [_snap("a", {"v": "x"}), _snap("b", {"v": None})]
        spec = infer_spec("triage", "res", _reads(("v", 1, True)), snaps)
        assert spec.data["structural"]["properties"]["v"] == {"type": ["string", "null"]}

    def test_consumer_warnings_carried_over(self) -> None:
        reads = _reads(("category", 1, True), warnings=["line 5: 'data' is used as a whole"])
        spec = infer_spec("triage", "res", reads, SNAPS)
        assert spec.warnings == ["line 5: 'data' is used as a whole"]

    def test_yaml_loads_as_spec_and_catches_rename(self) -> None:
        reads = _reads(("category", 3, False), ("confidence", 4, True))
        text = infer_spec("triage", "res", reads, SNAPS, name="t2r").to_yaml()
        assert text.startswith("# Generated by 'handshake infer' from res.py:run")
        spec = Spec.model_validate(yaml.safe_load(text)["spec"])
        assert spec.name == "t2r"

        for snap in SNAPS:
            assert validate_output(snap.output_data, spec).passed
        renamed = {"issue_type": "billing", "confidence": 0.9}
        result = validate_output(renamed, spec)
        assert not result.passed
        assert any("'category' is a required property" in e for e in result.errors)


NESTED = [
    _snap("a", {"customer": {"tier": "pro", "vip": True}, "billing": {"plan": "x"}}),
    _snap("b", {"customer": {"tier": "free"}}),
]


class TestInferNestedSpec:
    def test_nested_object_schema(self) -> None:
        reads = _reads(("customer.tier", 2, (True, False)), ("customer.vip", 3, (True, False)))
        structural = infer_spec("triage", "res", reads, NESTED).data["structural"]
        assert structural["required"] == ["customer"]
        assert structural["properties"]["customer"] == {
            "type": "object",
            "required": ["tier"],
            "properties": {"tier": {"type": "string"}, "vip": {"type": "boolean"}},
        }

    def test_required_only_where_parent_present(self) -> None:
        reads = _reads(("billing.plan", 4, (False, False)))
        spec = infer_spec("triage", "res", reads, NESTED)
        structural = spec.data["structural"]
        assert structural["required"] == []
        assert structural["properties"]["billing"]["required"] == ["plan"]
        assert spec.header[1:] == [
            "  billing: optional, read at line 4",
            "  billing.plan: required, read at line 4",
        ]

    def test_strict_nested_read_missing_warns(self) -> None:
        spec = infer_spec("triage", "res", _reads(("customer.vip", 5, True)), NESTED)
        assert spec.warnings == ["'customer.vip' is read with [] by res (line 5) but missing in: b"]

    def test_never_sent_parent_warns_once(self) -> None:
        spec = infer_spec("triage", "res", _reads(("account.owner.id", 6, False)), NESTED)
        assert spec.warnings == [
            "'account' is read by res (line 6) but triage never sent it in any snapshot"
        ]
        account = spec.data["structural"]["properties"]["account"]
        assert account["properties"]["owner"]["properties"] == {"id": {}}

    def test_nested_spec_catches_inner_rename(self) -> None:
        reads = _reads(("customer.tier", 2, False))
        text = infer_spec("triage", "res", reads, NESTED, name="t2r").to_yaml()
        spec = Spec.model_validate(yaml.safe_load(text)["spec"])
        for snap in NESTED:
            assert validate_output(snap.output_data, spec).passed
        result = validate_output({"customer": {"level": "pro"}}, spec)
        assert any("'tier' is a required property" in e for e in result.errors)


def test_read_lines_are_stored_by_path() -> None:
    reads = ConsumerReads(
        source="res.py:run",
        param="data",
        reads=[
            FieldRead(("customer", "tier"), 7, (True, False)),
            FieldRead(("customer", "tier"), 3, (True, False)),
            FieldRead(("priority",), 5, (False,)),
        ],
    )
    snaps = [_snap("a", {"customer": {"tier": "pro"}, "priority": "high"})]
    data = infer_spec("triage", "res", reads, snaps).data
    assert data["read_at"] == {"customer": [3, 7], "customer.tier": [3, 7], "priority": [5]}
    assert Spec.model_validate(data).read_at["customer.tier"] == [3, 7]
