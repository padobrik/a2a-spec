"""Tests for consumer-driven spec inference."""

from __future__ import annotations

from typing import Any

import yaml

from a2a_spec.infer.builder import infer_spec
from a2a_spec.infer.consumer import ConsumerReads, FieldRead
from a2a_spec.snapshot.fingerprint import Fingerprint
from a2a_spec.snapshot.store import Snapshot
from a2a_spec.spec.schema import Spec
from a2a_spec.spec.validator import validate_output


def _snap(scenario: str, output: dict[str, Any]) -> Snapshot:
    fp = Fingerprint(agent_id="triage", input_hash=scenario)
    return Snapshot(fingerprint=fp, scenario=scenario, input_data={}, output_data=output)


def _reads(*reads: tuple[str, int, bool], warnings: list[str] | None = None) -> ConsumerReads:
    return ConsumerReads(
        source="res.py:run",
        param="data",
        reads=[FieldRead(n, line, strict) for n, line, strict in reads],
        warnings=warnings or [],
    )


SNAPS = [
    _snap("a", {"category": "billing", "confidence": 0.9, "tags": ["x"], "unused": 1}),
    _snap("b", {"category": "shipping", "confidence": 1, "note": None}),
]


class TestInferSpec:
    def test_only_read_fields_become_contract(self) -> None:
        spec = infer_spec("triage", "res", _reads(("category", 3, True)), SNAPS)
        props = spec.data["structural"]["properties"]
        assert list(props) == ["category"]
        assert props["category"] == {"type": "string"}

    def test_always_sent_optional_read_is_required(self) -> None:
        spec = infer_spec("triage", "res", _reads(("category", 3, False)), SNAPS)
        assert spec.data["structural"]["required"] == ["category"]

    def test_sometimes_sent_optional_read_is_optional(self) -> None:
        spec = infer_spec("triage", "res", _reads(("tags", 3, False)), SNAPS)
        assert spec.data["structural"]["required"] == []
        assert spec.warnings == []

    def test_strict_read_missing_in_snapshot_warns(self) -> None:
        spec = infer_spec("triage", "res", _reads(("tags", 7, True)), SNAPS)
        assert spec.data["structural"]["required"] == ["tags"]
        assert spec.warnings == ["'tags' is read with [] by res (line 7) but missing in: b"]

    def test_never_sent_field_warns(self) -> None:
        spec = infer_spec("triage", "res", _reads(("issue_type", 4, False)), SNAPS)
        assert spec.data["structural"]["properties"]["issue_type"] == {}
        assert "never sent it" in spec.warnings[0]

    def test_types(self) -> None:
        reads = _reads(("confidence", 1, True), ("note", 2, False), ("tags", 3, False))
        props = infer_spec("triage", "res", reads, SNAPS).data["structural"]["properties"]
        assert props["confidence"] == {"type": "number"}
        assert props["note"] == {"type": "null"}
        assert props["tags"] == {"type": "array"}

    def test_mixed_types_listed(self) -> None:
        snaps = [_snap("a", {"v": "x"}), _snap("b", {"v": None})]
        spec = infer_spec("triage", "res", _reads(("v", 1, True)), snaps)
        assert spec.data["structural"]["properties"]["v"] == {"type": ["string", "null"]}

    def test_consumer_warnings_carried_over(self) -> None:
        reads = _reads(("category", 1, True), warnings=["line 5: 'data' is used as a whole"])
        spec = infer_spec("triage", "res", reads, SNAPS)
        assert spec.warnings == ["line 5: 'data' is used as a whole"]

    def test_yaml_loads_as_spec_and_catches_rename(self) -> None:
        reads = _reads(("category", 3, False), ("confidence", 4, True))
        text = infer_spec("triage", "res", reads, SNAPS, name="t2r").to_yaml()
        assert text.startswith("# Generated by 'a2aspec infer' from res.py:run")
        spec = Spec.model_validate(yaml.safe_load(text)["spec"])
        assert spec.name == "t2r"

        for snap in SNAPS:
            assert validate_output(snap.output_data, spec).passed
        renamed = {"issue_type": "billing", "confidence": 0.9}
        result = validate_output(renamed, spec)
        assert not result.passed
        assert any("'category' is a required property" in e for e in result.errors)
